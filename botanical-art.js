export function sketchPlant(kind, index) {
  const art = { broad, rolled, fern, spear }[kind] ?? broad;
  // Mirroring and slight lean preserve variety without distorting leaf anatomy.
  return `<g transform="${index % 3 === 1 ? 'translate(200 0) scale(-1 1)' : 'rotate(-3 100 310)'}">${art()}</g>`;
}
